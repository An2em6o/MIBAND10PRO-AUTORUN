-- 把参数变成 POSIX 安全的单引号字面量。单引号内部没有任何转义机制,
-- 遇到引号只能"关引号 + 转义引号 + 重开引号"。
local function quote_arg(value)
  local pieces = { "'" }
  for ch in tostring(value):gmatch(".") do
    if ch == "'" then
      pieces[#pieces + 1] = "'\\''"
    else
      pieces[#pieces + 1] = ch
    end
  end
  pieces[#pieces + 1] = "'"
  return table.concat(pieces)
end

