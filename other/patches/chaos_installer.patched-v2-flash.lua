-- ===== 开机自启动(设备侧那半) —— 按"新标准"重写 =====
-- ★ 新标准(2026-10-04 用户定), 三条:
--   ① 模块**只投文件**: 把启动命令写进 <RC_DIR>/<名字>.sh, 注册就完了;
--   ② **没有 <RC_DIR> ⇒ 报错「管理器没装」** —— 不自己建目录、不退到老做法, 一个字节都不写;
--   ③ `/data/rc` 是**产物**, 由管理器检测到新切片后改写; 模块**永不**碰它。
--   附带: 模块也**不碰 flash** —— flash 里那句 `sh /data/rc &` 归管理器的"装 init rc"。
-- 与老做法的差别(老做法已废弃, 但必须知道差在哪, 否则会以为自己漏了什么):
--   老: rc 脚本落在 /data/chaos/rc, 再往 /data/rc **追加一行** "sh /data/chaos/rc &";
--   新: 脚本直接落 /data/rc.d/chaos.sh, 那一行由管理器生成。**二跳没了**。
-- 底下 LEGACY_* 三个常量**只服务于"清掉旧版残留"**, 不再被任何写盘路径使用 ——
-- 不复原它们就是个雷: 旧行还在 /data/rc 里, 每次开机去跑一个已经被删掉的 /data/chaos/rc。
-- 节奏(下面两个延时)保持不变: 8s 是等开机负载过去, 15s 是等模块把 3 步序列走完。
-- 为什么不能 rc 里直接 dd 那几条安装命令: 模块的 write 是**同步**的, 在 sh 任务里
-- 同步跑注册链会挂死到看门狗 —— 所以只能走"入环即返回"的 CMD_BOOT_DQ。
local RC_DIR = "/data/rc.d"                       -- 管理器的注册目录(新标准唯一入口)
local RC_SH  = RC_DIR .. "/chaos.sh"              -- 本模块的注册脚本
local LEGACY_RC_PATH = "/data/rc"                 -- 只读: 用来摘旧版残留那一行
local LEGACY_HOP = "sh /data/chaos/rc &"          -- 只读: 旧版追加的那一行
local LEGACY_CHAOS_RC = DATA_DIR .. "/rc"         -- 只删: 旧版的 rc 脚本
local BOOT_FRAME = DATA_DIR .. "/boot.bin"
local FLAG_ON = DATA_DIR .. "/autostart.on"
