-- u32 小端打包: 逐字节压进 table 再拼, 避免一行四个取模堆在一起
local function u32le(value)
  local n = math.floor(value)
  local pieces = {}
  for _ = 1, 4 do
    pieces[#pieces + 1] = string.char(n % 0x100)
    n = math.floor(n / 0x100)
  end
  return table.concat(pieces)
end

-- ===================== 开机自启动: 落盘 + 开关 =====================

-- rc 脚本全文。语法**逐条**取自同机那个平台已经跑通的 /data/rc 子集:
--   set +e / if [ -f ]…fi / rm -f / echo > 、>> / sleep / insmod / dd
-- 不能用的(没有证据): && || [ -e ] [ ! ] $( ) —— nsh 是子集解释器。
-- 防砖语义: 开头先删开关, 整段(含安全窗)走完才重建; 窗内掉电/看门狗/主动重启
-- 都让开关停在【关】, 下次开机整段跳过。这就是"防砖"的全部机制。
local function build_chaos_rc()
  local L = {}
  local function w(s) L[#L + 1] = s end
  w("set +e")
  w("if [ -f " .. FLAG_ON .. " ];then")
  w("rm -f " .. FLAG_ON)
  w("echo start > " .. AS_LOG)
  w("echo delay=" .. AUTOSTART_DELAY .. " >> " .. AS_LOG)
  w("sleep " .. AUTOSTART_DELAY)
  w("insmod " .. SUPERVISOR_PATH .. " chaos_sup")
  w("echo insmod >> " .. AS_LOG)
  w("dd if=" .. DEVICE_PATH .. " of=" .. DATA_DIR .. "/stage1.bin bs="
    .. STATUS_SIZE .. " count=1 conv=notrunc")
  w("dd if=" .. BOOT_FRAME .. " of=" .. DEVICE_PATH .. " bs=16 count=1 conv=notrunc")
  w("echo boot_cmd_sent >> " .. AS_LOG)
  w("echo safehold=" .. SAFETY_WAIT_S .. " >> " .. AS_LOG)
  w("sleep " .. SAFETY_WAIT_S)
  w("echo safehold_ok >> " .. AS_LOG)
  w("dd if=" .. DEVICE_PATH .. " of=" .. DATA_DIR .. "/stage3.bin bs="
    .. STATUS_SIZE .. " count=1 conv=notrunc")
  w("echo done >> " .. AS_LOG)
  w("echo on > " .. FLAG_ON)
  w("echo cleared >> " .. AS_LOG)
  w("fi")
  return table.concat(L, "\n") .. "\n"
end

-- 16 字节命令帧: magic | cmd | arg0 | arg1。
-- 两个"魔数"都挑成了可打印 ASCII ⇒ 整串就是 "1CHS3CHS" + 8 个 0, 落盘后肉眼就能核。
local function build_boot_frame()
  return u32le(CMD_MAGIC) .. u32le(CMD_BOOT_DQ) .. u32le(0) .. u32le(0)
end

local function autostart_staged()
  local frame = read_all(BOOT_FRAME)
  local rc = read_all(CHAOS_RC)
  local cur = read_all(RC_PATH)
  local hop = type(cur) == "string" and cur:find(RC_HOP, 1, true) ~= nil
  return frame == build_boot_frame() and type(rc) == "string" and #rc > 0 and hop
end

local function autostart_install()
  exec("mkdir -p " .. DATA_DIR)
  local frame = build_boot_frame()
  local ok, err = write_file(BOOT_FRAME, frame)
  if not ok then return false, err end
  ok, err = write_file(CHAOS_RC, build_chaos_rc())
  if not ok then return false, err end
  -- 往 /data/rc 末尾补二跳。**幂等**: 已经有那一行就不再追加(重复追加会被执行两次)。
  -- 注意 /data/rc 可能已经被上游平台占用 —— 只追加一行, 绝不整体覆盖。
  local cur = read_all(RC_PATH)
  if type(cur) ~= "string" then cur = "" end
  if not cur:find(RC_HOP, 1, true) then
    local f = io.open(RC_PATH, "a")
    if not f then return false, "打不开 " .. RC_PATH end
    local wok = pcall(f.write, f, RC_HOP .. "\n")
    local cok = pcall(f.close, f)
    if not wok or not cok then return false, "追加 " .. RC_PATH .. " 失败" end
  end
  if not autostart_staged() then return false, "落盘核对不过" end
  return true
end

-- 只摘掉我们自己那一行, 不动 /data/rc 里别人的内容。
local function autostart_strip()
  local cur = read_all(RC_PATH)
  if type(cur) ~= "string" or #cur == 0 then return true end
  if not cur:find(RC_HOP, 1, true) then return true end
  local scan = cur
  if scan:sub(-1) ~= "\n" then scan = scan .. "\n" end
  local keep = {}
  for line in scan:gmatch("([^\n]*)\n") do
    if line:gsub("%s+$", "") ~= RC_HOP then keep[#keep + 1] = line end
  end
  local out = table.concat(keep, "\n")
  if #out > 0 then out = out .. "\n" end
  return write_file(RC_PATH, out)
end

