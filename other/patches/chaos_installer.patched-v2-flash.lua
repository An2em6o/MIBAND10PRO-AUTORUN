-- ===================== rcS hook: flash 里那句开机钩子 =====================
-- 为什么需要它(硬证据, 别删这段):
--   原版固件的 /etc/init.d/rcS 末行就是 `exit`; 整枚 vela_ap.bin 里 `/data/rc`
--   出现 **0 次**。也就是说固件**自己永远不会**去跑 /data/rc。
--   所以"装自启文件"只把文件摆好了 —— 没有这一句开机钩子, 开机什么都不发生,
--   而且是**静默地**不发生(界面全绿)。
-- 做法: 把 AP 分区 /etc ROMFS 里 rcS inode 的末行 `exit` 换成 `sh /data/rc &`,
--       同时改这个 inode 的 size(332) 与 checksum; 其余字节一个都不动。
-- 纪律(任何一条不符 ⇒ 一个字节都不写):
--   [门1] 固件版本: 内置原块只来自 3.101.043, 版本不符则 flash 部分整体停用;
--   [门2] 载荷自检: 原块 adler / 载荷 adler / romfs 超级块 / rcS inode 四处自检;
--   [门3] 写前    : 目标块必须"前段 + 本身段 + 后段"三段逐字节等于内置原块;
--   [门4] 写后    : 回读逐字节 == 载荷, 且前后相邻块的 adler 不变。
-- 目标定位: 三个候选 (dev, byteoff) 轮流探测, 谁认出来锁谁; 一个都没认出来 ⇒ 不写。
-- 因为是写 flash, 与"装自启文件"性质不同, 所以界面上是**两段式确认**(按两次才动手)。
