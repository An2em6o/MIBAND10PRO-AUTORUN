-- 桌面注册项都不在这张表里** —— 那是主功能, 移除自启动时必须原样留着。
local AS_FILES = {
  CHAOS_RC, BOOT_FRAME, FLAG_ON, AS_LOG,
  DATA_DIR .. "/stage1.bin", DATA_DIR .. "/stage3.bin",
  DATA_DIR .. "/apblk.bin", DATA_DIR .. "/fwver.tmp",
