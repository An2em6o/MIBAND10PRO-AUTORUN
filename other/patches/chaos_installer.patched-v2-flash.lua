make_button(as_view, "开自启动", -20, "primary", function()
  as_armed = ""
  if not autostart_staged() then as_set("先按「装自启文件」", V_WARN); return end
  if autostart_flag(true) then
    as_set("自启动【开】 下次开机自动注册", V_OK)
  else
    as_set("写开关失败", V_ERR)
  end
end, AS_BTN)

make_button(as_view, "关自启动", 44, "ghost", function()
  as_armed = ""
  if autostart_flag(false) then
    as_set("自启动【关】 下次开机不注册", V_WARN)
  else
    as_set("删开关失败", V_ERR)
  end
end, AS_BTN)

make_button(as_view, "移除文件", 108, "danger", function()
  if runner then as_set("正在运行, 请等待", V_WARN); return end
  if as_armed ~= "remove" then
    as_armed = "remove"
    as_set("再按一次: 还原hook+清文件", V_WARN)
    return
  end
  as_armed = ""
  local ok, msg = as_remove_all()
  as_set(msg, ok and V_OK or V_ERR)
end, AS_BTN)

make_button(as_view, "< 返回", 172, "ghost", function()
  as_armed = ""            -- 离开这一页就清闸(免得下次进来第一按直接动手)
  as_set(autostart_state_text(), V_TXT2)
  view_show("main")
end, AS_BTN)
